# Read all three Asian language files
languages = {
    'zh': 'intents/intents_zh.json',
    'ja': 'intents/intents_ja.json',
    'ko': 'intents/intents_ko.json'
}

for lang_code, file_path in languages.items():
    print(f"\nProcessing {lang_code.upper()}...")
    with open(file_path, 'r', encoding='utf-8') as f:
        data = json.load(f)
    
    # Update each expandable intent
    expanded_count = 0
    for intent in data['intents']:
        tag = intent['tag']
        
        if tag in expansion_map:
            lang_key = f'{lang_code}_patterns'
            if lang_key in expansion_map[tag]:
                new_patterns = expansion_map[tag][lang_key]
                old_count = len(intent['patterns'])
                intent['patterns'] = new_patterns
                new_count = len(intent['patterns'])
                print(f"  {tag}: {old_count} → {new_count} patterns")
                expanded_count += new_count - old_count
    
    # Save the file
    with open(file_path, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
    
    print(f"  → Total expansion: +{expanded_count} patterns")

print("\n" + "=" * 70)
print("Expansion complete! All Asian languages significantly expanded.")
print("=" * 70)
