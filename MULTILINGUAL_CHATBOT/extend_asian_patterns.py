# Read all three Asian language files
languages = {
    'zh': 'intents/intents_zh.json',
    'ja': 'intents/intents_ja.json',
    'ko': 'intents/intents_ko.json'
}

for lang_code, file_path in languages.items():
    print(f"Extended expansion for {lang_code.upper()}...")
    with open(file_path, 'r', encoding='utf-8') as f:
        data = json.load(f)
    
    expanded_count = 0
    for intent in data['intents']:
        tag = intent['tag']
        
        if tag in extended_expansion:
            lang_key = f'{lang_code}_patterns'
            if lang_key in extended_expansion[tag]:
                new_patterns = extended_expansion[tag][lang_key]
                old_count = len(intent['patterns'])
                intent['patterns'] = new_patterns
                new_count = len(intent['patterns'])
                print(f"  {tag}: {old_count} → {new_count} patterns")
                expanded_count += new_count - old_count
    
    # Save the file
    with open(file_path, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
    
    print(f"  → Total expansion: +{expanded_count} patterns\n")

print("=" * 70)
print("Extended expansion complete! Preparing for full retrain...")
