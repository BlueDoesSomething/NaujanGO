// Default supported languages (fallback if API fails)
const defaultSupportedLanguages = [
  { code: 'en', label: 'English', flag: '🇺🇸', nativeName: 'English' },
  { code: 'es', label: 'Spanish', flag: '🇪🇸', nativeName: 'Español' },
  { code: 'tl', label: 'Tagalog', flag: '🇵🇭', nativeName: 'Tagalog' },
  { code: 'zh', label: 'Chinese', flag: '🇨🇳', nativeName: '中文' },
  { code: 'ja', label: 'Japanese', flag: '🇯🇵', nativeName: '日本語' },
  { code: 'ko', label: 'Korean', flag: '🇰🇷', nativeName: '한국어' },
  { code: 'fr', label: 'French', flag: '🇫🇷', nativeName: 'Français' },
  { code: 'de', label: 'German', flag: '🇩🇪', nativeName: 'Deutsch' }
]

export function LanguageProvider({ children }) {
  const { user, isLoggedIn } = useAuth();
  const [language, setLanguage] = useState(() => {
    // Priority: saved key, then legacy key, then always default to 'en' (not browser language)
    const saved = (() => { try { return localStorage.getItem('naujango_language') } catch (e) { return null } })()
    const legacy = (() => { try { return localStorage.getItem('preferredLanguage') } catch (e) { return null } })()
    return saved || legacy || 'en'
  })
  const [supportedLanguages, setSupportedLanguages] = useState(defaultSupportedLanguages)
  const [loading, setLoading] = useState(false)

  // Load supported languages from database
  useEffect(() => {
    const loadSupportedLanguages = async () => {
      try {
        setLoading(true)
        const response = await fetchLanguages()
        const dbLanguages = response.data.map(lang => {
          // Map database languages to frontend format
          const defaultLang = defaultSupportedLanguages.find(dl => dl.code === lang.language_code)
          return {
            code: lang.language_code,
            label: lang.language_name,
            flag: defaultLang?.flag || '🌍',
            nativeName: defaultLang?.nativeName || lang.language_name
          }
        })
        
        if (dbLanguages.length > 0) {
          setSupportedLanguages(dbLanguages)
        }
      } catch (error) {
        console.error('Failed to load languages from database:', error)
        // Keep using default languages as fallback
      } finally {
        setLoading(false)
      }
    }

    loadSupportedLanguages()
  }, [])

  // Load user language preference when user logs in
  useEffect(() => {
    if (isLoggedIn && user?.user_id) {
      const loadUserLanguagePreference = async () => {
        try {
          const response = await getUserLanguagePreference(user.user_id)
          const userLang = response.data.language_code
          if (userLang && userLang !== language) {
            setLanguage(userLang)
            try { localStorage.setItem('naujango_language', userLang) } catch (e) {}
          }
        } catch (error) {
          console.error('Failed to load user language preference:', error)
        }
      }

      loadUserLanguagePreference()
    }
  }, [isLoggedIn, user])

  // Save language preference to localStorage and database
  useEffect(() => {
    try {
      localStorage.setItem('naujango_language', language)
    } catch (err) {
      // ignore localStorage write errors
    }

    // Update document language attribute and direction for accessibility
    try {
      document.documentElement.lang = language || 'en'
      const rtl = ['ar', 'he', 'fa', 'ur']
      document.documentElement.dir = rtl.includes(language) ? 'rtl' : 'ltr'
    } catch (err) {
      // not running in browser
    }

    // Update user preference in database if logged in
    if (isLoggedIn && user?.user_id) {
      const updateUserPreference = async () => {
        try {
          await updateUserLanguagePreference(user.user_id, language)
        } catch (error) {
          console.error('Failed to update user language preference:', error)
        }
      }

      updateUserPreference()
    }
  }, [language, isLoggedIn, user])

  const t = (key) => {
    const dict = translations[language] || translations.en
    return dict[key] || translations.en[key] || key
  }

  const changeLanguage = (newLang) => {
    if (!newLang || newLang === language) return

    try {
      localStorage.setItem('naujango_language', newLang)
    } catch (err) {
      // ignore localStorage write errors
    }

    setLanguage(newLang)
  }

  const getCurrentLanguage = () => {
    return supportedLanguages.find(l => l.code === language) || supportedLanguages[0]
  }

  const value = useMemo(() => ({ 
    language, 
    setLanguage: changeLanguage, 
    t, 
    supportedLanguages,
    getCurrentLanguage,
    loading
  }), [language, supportedLanguages, loading])

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>
}

export function useLanguage() {
  const ctx = useContext(LanguageContext)
  if (!ctx) throw new Error('useLanguage must be used within LanguageProvider')
  return ctx
}

export default LanguageContext








